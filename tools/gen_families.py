#!/usr/bin/env python3
"""Generate src/detector/families/*.rs from upstream AprilTag's family sources in vendor/apriltag.

Codewords and their bit order are upstream's, verbatim: bit k (most significant first) is the cell
(bit_x[k], bit_y[k]) relative to the border square's top-left cell, and a set bit is a white printed
cell. One change: upstream's frame is turned 180 degrees (x -> width_at_border - 1 - x, likewise y),
so the detector's corner order is OpenCV's (the printed tag's top-left corner first). Usage:

    python3 -I tools/gen_families.py [vendor/apriltag [src/detector/families]]
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def parse(path: Path) -> dict:
    text = path.read_text()

    def field(name: str) -> str:
        return re.search(rf"tf->{name} = ([^;]+);", text).group(1).strip()

    nbits = int(field("nbits"))
    ncodes = int(field("ncodes"))
    codes = re.findall(r"\b(0x[0-9a-fA-F]+)UL\b", text)
    bit_x = {int(i): int(v) for i, v in re.findall(r"bit_x\[(\d+)\] = (-?\d+);", text)}
    bit_y = {int(i): int(v) for i, v in re.findall(r"bit_y\[(\d+)\] = (-?\d+);", text)}
    assert len(codes) == ncodes, path
    assert sorted(bit_x) == sorted(bit_y) == list(range(nbits)), path
    width = int(field("width_at_border"))
    notice = re.match(r"\s*/\*(.*?)\*/", text, re.S).group(1)
    return {
        "name": field("name").removeprefix('strdup("').removesuffix('")'),
        "file": path.name,
        "width": width,
        "total_width": int(field("total_width")),
        "reversed": field("reversed_border") == "true",
        "min_distance": int(field("h")),
        "nbits": nbits,
        "x": [width - 1 - bit_x[k] for k in range(nbits)],
        "y": [width - 1 - bit_y[k] for k in range(nbits)],
        "codes": [int(c, 16) for c in codes],
        "notice": [line.strip() for line in notice.strip().splitlines()],
    }


def emit(f: dict, commit: str) -> str:
    const = f["name"].upper()
    out = [
        "// @generated by tools/gen_families.py; do not edit.",
        f"// {f['name']} from upstream AprilTag {f['file']} (vendor/apriltag), commit {commit[:12]}:",
        "// its codewords and bit order, in a frame turned 180 degrees (see gen_families.py). Notice:",
        "//",
    ]
    out += [f"// {line}".rstrip() for line in f["notice"]]
    out += [
        "",
        "use super::super::family::Family;",
        "",
        "#[rustfmt::skip]",
        f"pub static {const}: Family = Family {{",
        f'    name: "{f["name"]}",',
        f"    width: {f['width']},",
        f"    total_width: {f['total_width']},",
        f"    reversed: {'true' if f['reversed'] else 'false'},",
        f"    min_distance: {f['min_distance']},",
        f"    nbits: {f['nbits']},",
        f"    x: &[{', '.join(map(str, f['x']))}],",
        f"    y: &[{', '.join(map(str, f['y']))}],",
        "    codes: &[",
    ]
    codes = f["codes"]
    for i in range(0, len(codes), 8):
        out.append("        " + ", ".join(f"{c:#x}" for c in codes[i : i + 8]) + ",")
    out += ["    ],", "};"]
    return "\n".join(out) + "\n"


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "vendor/apriltag"
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "src/detector/families"
    commit = re.search(r"commit\s+`([0-9a-f]{40})`", (src / "README.md").read_text()).group(1)
    families = [parse(p) for p in sorted(src.glob("tag*.c"))]
    dst.mkdir(parents=True, exist_ok=True)
    for f in families:
        (dst / f"{f['name'].lower()}.rs").write_text(emit(f, commit))
    families.sort(key=lambda f: f["name"].lower())
    mods = "".join(f"mod {f['name'].lower()};\n" for f in families)
    uses = "".join(f"pub use {f['name'].lower()}::{f['name'].upper()};\n" for f in families)
    # tag36h11 first: it is the FRC family and the default.
    families.sort(key=lambda f: f["name"] != "tag36h11")
    table = "".join(f"    &{f['name'].upper()},\n" for f in families)
    (dst / "mod.rs").write_text(
        "// @generated by tools/gen_families.py; do not edit.\n"
        "//! AprilTag families, from upstream AprilTag (BSD-2-Clause, vendor/apriltag); see each file's notice.\n\n"
        + mods
        + "\n"
        + uses
        + "\nuse super::family::Family;\n\n"
        + "/// Every supported family, tag36h11 (the default) first.\n"
        + "pub static ALL: &[&Family] = &[\n"
        + table
        + "];\n"
    )


if __name__ == "__main__":
    main()
